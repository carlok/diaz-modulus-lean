"""Referee B: exact failure test for a concrete graded matrix over Q, and the 5 x 8 example."""
from fractions import Fraction as Fr
import itertools, random, sys

def rref(rows,n):
    rows=[list(map(Fr,r)) for r in rows]; piv=0; out=[]
    for c in range(n):
        p=None
        for i in range(piv,len(rows)):
            if rows[i][c]!=0: p=i;break
        if p is None: continue
        rows[piv],rows[p]=rows[p],rows[piv]
        inv=1/rows[piv][c]; rows[piv]=[x*inv for x in rows[piv]]
        for i in range(len(rows)):
            if i!=piv and rows[i][c]!=0:
                f=rows[i][c]; rows[i]=[x-f*y for x,y in zip(rows[i],rows[piv])]
        piv+=1
    return tuple(tuple(r) for r in rows[:piv])
def rank(rows,n=None):
    if not rows: return 0
    return len(rref(rows,n if n is not None else len(rows[0])))
def perp(sp,n=3):
    """annihilator of span(sp) in the dual"""
    R=rref(sp,n) if sp else ()
    pivs=[next(j for j,x in enumerate(r) if x!=0) for r in R]
    free=[j for j in range(n) if j not in pivs]; out=[]
    for f in free:
        v=[Fr(0)]*n; v[f]=Fr(1)
        for r,p in zip(R,pivs): v[p]=-r[f]
        out.append(tuple(v))
    return rref(out,n) if out else ()
def add(u,v,n=3): return rref(list(u)+list(v),n) if (u or v) else ()
def meet(u,v,n=3): return perp(add(perp(u,n),perp(v,n),n),n)
def dim(u): return len(u)

def analyse(xs,a,ys,b,S=None,n=3):
    """xs,ys rational vectors, a,b weights. Returns dict with rank, theta, fail status.
    theta = min over U of (l-c(U))/r(U), U in the lattice generated by P_a and Q_b^perp."""
    d,l=len(xs),len(ys)
    C=[[sum(Fr(p)*Fr(q) for p,q in zip(x,y)) for y in ys] for x in xs]
    if S is not None:
        for i in range(d):
            for j in range(l):
                if C[i][j]!=0: assert a[i]+b[j] in S,(i,j,a[i]+b[j])
    rk=rank(C,l)
    P={};Q={}
    for x,w in zip(xs,a): P.setdefault(w,[]).append(x)
    for y,w in zip(ys,b): Q.setdefault(w,[]).append(y)
    P={w:rref(v,n) for w,v in P.items()}; Q={w:rref(v,n) for w,v in Q.items()}
    freer=all(dim(P[w])==sum(1 for t in a if t==w) for w in P)
    freec=all(dim(Q[w])==sum(1 for t in b if t==w) for w in Q)
    gens=set(P.values())|{perp(q,n) for q in Q.values()}|{rref([[1 if i==j else 0 for j in range(n)] for i in range(n)],n)}
    gens=set(g for g in gens if g)
    lat=set(gens)
    for _ in range(3):
        new=set()
        L=list(lat)
        for u,v in itertools.combinations(L,2):
            for w in (add(u,v,n),meet(u,v,n)):
                if w and w not in lat: new.add(w)
        if not new: break
        lat|=new
    # also the row-point spans
    best=None;arg=None;table=[]
    for U in lat:
        r=sum(dim(p)+dim(U)-dim(add(p,U,n)) for p in P.values())
        Up=perp(U,n)
        c=sum(dim(q)+dim(Up)-dim(add(q,Up,n)) for q in Q.values())
        if r==0: continue
        table.append((U,r,c))
        val=Fr(l-c,r)
        if best is None or val<best: best=val;arg=(U,r,c)
    return dict(d=d,l=l,rank=rk,free_rows=freer,free_cols=freec,theta=best,arg=arg,
                fails=(d-rk)*best>rk,lattice=len(lat),table=table,C=C)

def brute_random_subpairs(xs,a,ys,b,theta,trials=3000,seed=1):
    """Non-homogeneous row subspaces R: columns C(R)= common kernel over all sigma. Check no ratio below theta."""
    rnd=random.Random(seed); d,l=len(xs),len(ys)
    C=[[sum(Fr(p)*Fr(q) for p,q in zip(x,y)) for y in ys] for x in xs]
    sig={}
    for i in range(d):
        for j in range(l):
            if C[i][j]!=0: sig.setdefault(a[i]+b[j],[[Fr(0)]*l for _ in range(d)])[i][j]=C[i][j]
    bad=0
    for t in range(trials):
        k=rnd.randint(1,d)
        # sparse random row combinations: sparse so that the column kernel is non-trivial
        R=[]
        for _ in range(k):
            v=[Fr(0)]*d
            for i in rnd.sample(range(d),rnd.randint(1,2)): v[i]=Fr(rnd.randint(-2,2))
            R.append(v)
        if rank(R,d)==0: continue
        rr=rank(R,d)
        eqs=[]
        for s,Ms in sig.items():
            for v in R:
                eqs.append([sum(v[i]*Ms[i][j] for i in range(d)) for j in range(l)])
        cdim=l-rank(eqs,l)
        if Fr(l-cdim,rr)<theta: bad+=1
    return bad

