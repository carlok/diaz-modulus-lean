#!/usr/bin/env python3
"""Referee B: row-first exhaustive attack on Theorem 3.

For fixed row weights and a fixed point/line geometry the best column set is forced: for each
integer b take Q_b = annihilator of all P_a with a+b not in S. Adding columns never hurts (*)
(d-3)(l-c(U)) > 3 r(U), so only this maximal matrix must be tested, and every l is covered at once.

Assumed (elementary, rederived by hand): stable, d<=l, so x_p<=1 (Step 1): distinct points, at most one
2-dimensional class L, no point on L. Connected bipartite graph, so consecutive distinct weights differ by at
most span(S). Geometry: freest linear space generated by a subset of the forced sets Z_b, |Z_b|>=3.
Extra collinearity adds no column and only raises r, so the freest one is the best case. The abstract test can
give a false positive (non-realisable), never a false negative.
"""
import sys, time, itertools, json
pop=lambda x: bin(x).count('1')

def closure(lines, new, allmask=None):
    lines=set(lines); cur=new
    changed=True
    while changed:
        changed=False
        for m in list(lines):
            if pop(m&cur)>=2:
                lines.discard(m); cur|=m; changed=True
    lines.add(cur)
    return frozenset(lines)

def evaluate(state,cols,k,eta,d):
    """cols: list of (type,mask): types 'full','pc','lc','L'. Returns (l,fails,witness)"""
    full=0;pc=[0]*k;cL=0;lc={}
    for t,Z in cols:
        if t==0: full+=1
        elif t==1:
            pc[Z]+=1
        elif t==3: cL+=1
        else:
            # line class needs Z collinear in state
            if pop(Z)==2:
                m=Z
                for ln in state:
                    if Z&ln==Z: m=ln;break
                lc[m]=lc.get(m,0)+1
            else:
                for ln in state:
                    if Z&ln==Z:
                        lc[ln]=lc.get(ln,0)+1;break
    spc=sum(pc)
    l=3*full+2*spc+sum(lc.values())+cL
    D=d-3
    if D*l<=3*d: return l,False,('whole',)
    # pairs not on a state line
    cand=set(state)
    for i in range(k):
        for j in range(i+1,k):
            m=(1<<i)|(1<<j)
            if not any(m&ln==m for ln in state): cand.add(m)
    for m in cand:
        c=full+cL*0+sum(pc[i] for i in range(k) if m>>i&1)+lc.get(m,0)
        r=pop(m)+eta
        if D*(l-c)<=3*r: return l,False,('line',m)
    for i in range(k):
        # generic line through p_i only
        if D*(l-full-pc[i])<=3*(1+eta): return l,False,('gline',i)
        beta=2*full+spc+pc[i]+sum(v for m,v in lc.items() if m>>i&1)
        if D*(l-beta)<=3: return l,False,('pt',i)
    if eta:
        if D*(l-full-cL)<=3*2: return l,False,('L',)
        if D*(l-full)<=3: return l,False,('g0',)
        beta=2*full+spc+cL+(max(lc.values()) if lc else 0)
        if D*(l-beta)<=3: return l,False,('ptL',)
    return l,True,None

def scan(S,weights,Lidx,minl=0):
    """weights: distinct ints, Lidx: index of 2-dim class or None. Returns list of hits."""
    d=len(weights)+(1 if Lidx is not None else 0)
    eta=1 if Lidx is not None else 0
    pts=[w for i,w in enumerate(weights) if i!=Lidx]
    k=len(pts)
    aL=weights[Lidx] if eta else None
    lo=min(S)-max(weights); hi=max(S)-min(weights)
    Sset=S if isinstance(S,(set,frozenset)) else set(S)
    allm=(1<<k)-1
    cols=[];force=set()
    for b in sorted({x-w for x in Sset for w in weights}):
        inL=eta and (aL+b not in Sset)
        Z=0
        for i,w in enumerate(pts):
            if w+b not in Sset: Z|=1<<i
        if eta and inL:
            if Z==0: cols.append((3,0))
            continue
        if Z==0: cols.append((0,0))
        elif pop(Z)==1: cols.append((1,Z.bit_length()-1))
        else:
            cols.append((2,Z))
            if pop(Z)>=3: force.add(Z)
    # quick bound on l
    ub=sum({0:3,1:2,2:1,3:1}[t] for t,_ in cols)
    if (d-3)*ub<=3*d or ub<minl: return [],0
    hits=[];seen=set();stack=[frozenset()]
    nstates=0
    while stack:
        st=stack.pop()
        if st in seen: continue
        seen.add(st); nstates+=1
        l,f,w=evaluate(st,cols,k,eta,d)
        if f: hits.append((tuple(sorted(st)),l))
        for Z in force:
            if any(Z&ln==Z for ln in st): continue
            ns=closure(st,Z)
            if not eta and any(ln==allm for ln in ns): continue
            stack.append(ns)
    return hits,nstates

def tuples(rho,G):
    def rec(pre,left):
        if left==0: yield tuple(pre); return
        for g in range(1,G+1):
            pre.append(pre[-1]+g)
            yield from rec(pre,left-1)
            pre.pop()
    yield from rec([0],rho-1)

def run(S,d,G,limit,minl=0,sym=True):
    t0=time.time();tot=0;states=0;allhits=[]
    done_all=True
    for eta in (0,1):
        rho=d-eta
        if eta and rho<1: continue
        count=0
        for w in tuples(rho,G):
            gaps=[w[i+1]-w[i] for i in range(rho-1)]
            refl=sym and tuple(gaps)>tuple(reversed(gaps))
            if refl: continue
            for Lidx in ([None] if not eta else range(rho)):
                h,ns=scan(S,w,Lidx,minl)
                tot+=1;states+=ns
                for x in h: allhits.append((w,Lidx,x))
            count+=1
            if time.time()-t0>limit: done_all=False;break
        if not done_all: break
    return dict(d=d,G=G,tuples=tot,states=states,hits=len(allhits),sample=allhits[:6],complete=done_all,sec=round(time.time()-t0,1))

